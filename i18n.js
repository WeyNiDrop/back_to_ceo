const GAME_LANGUAGE_KEY = 'backtoceo_language';

function readGameLanguage() {
  try {
    const language = localStorage.getItem(GAME_LANGUAGE_KEY);
    return language === 'zh-CN' || language === 'en' ? language : null;
  } catch {
    return null;
  }
}

let selectedLanguage = readGameLanguage();

function getGameLanguage() {
  return selectedLanguage || 'zh-CN';
}

function translate(source, ...values) {
  const text = getGameLanguage() === 'en' && Object.hasOwn(ENGLISH_TEXT, source) ? ENGLISH_TEXT[source] : source;
  return values.length ? text.replace(/\{(\d+)\}/g, (placeholder, index) => values[index] ?? placeholder) : text;
}

function formatCash(amount) {
  if (getGameLanguage() === 'zh-CN') return `$${amount.toLocaleString('zh-CN')}万`;
  if (amount === 0) return '$0';
  if (amount >= 100) {
    return `$${(amount / 100).toLocaleString('en-US', { maximumFractionDigits: 2 })}M`;
  }
  return `$${(amount * 10).toLocaleString('en-US')}K`;
}

function applyPageLanguage() {
  document.documentElement.lang = getGameLanguage();
  document.title = translate('Back To CEO 重回巅峰之路');
  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', translate(element.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    element.alt = translate(element.dataset.i18nAlt);
  });
}

function setGameLanguage(language) {
  selectedLanguage = language;
  try {
    localStorage.setItem(GAME_LANGUAGE_KEY, language);
  } catch {
    // 私密模式下仍可在当前页面使用所选语言。
  }
  applyPageLanguage();
}
